#!/usr/bin/env python3
"""ymfm_opl.cpp 에서 YM3812(OPL2)/YMF262(OPL3)에 필요한 부분만 남긴 ymfm_opl_min.cpp 생성.
업스트림 YMFM 소스는 수정하지 않는다(ref/ymfm 은 pin된 원본). 마커 문자열 기반이라 줄번호에 의존하지 않는다.
제거: log_keyon(std::string/snprintf 의존), OPLL, YM3526, Y8950, YMF289B, YMF278B, OPLL계열, OPL4 명시적 인스턴스화.
"""
import sys, re
src, dst = sys.argv[1], sys.argv[2]
L = open(src, encoding='utf-8').read().split('\n')

def find(pat, start=0):
    for i in range(start, len(L)):
        if re.search(pat, L[i]): return i
    raise SystemExit('marker not found: ' + pat)

def star_before(i):            # 해당 제목 바로 위의 //*** 줄
    while not L[i].startswith('//*****'): i -= 1
    return i

keep = [True] * len(L)
def drop(a, b):                # [a, b)
    for i in range(a, b): keep[i] = False

# 1) log_keyon (OPL base)
a = find(r'//  log_keyon - log a key-on event') - 1
b = find(r'//  OPLL SPECIFICS'); b = star_before(b)
drop(a, b)
# 2) OPLL SPECIFICS ~ YM3812 직전(YM3526, Y8950 포함)
a = star_before(find(r'//  OPLL SPECIFICS'))
b = star_before(find(r'//  YM3812\s*$'))
drop(a, b)
# 3) YMF289B 이후 ~ EXPLICIT INSTANTIATION 직전
a = star_before(find(r'//  YMF289B\s*$'))
b = star_before(find(r'//  EXPLICIT INSTANTIATION'))
drop(a, b)
# 4) OPL4 명시적 인스턴스화 제거
for i, s in enumerate(L):
    if re.match(r'template class (opl_registers_base<4>|fm_engine_base<opl_registers_base<4>>);', s): keep[i] = False

out = [s for s, k in zip(L, keep) if k]
open(dst, 'w', encoding='utf-8', newline='\n').write('// GENERATED by tools/gen_min.py from ymfm_opl.cpp - DO NOT EDIT\n' + '\n'.join(out))
print('kept %d / %d lines' % (len(out), len(L)))