#!/usr/bin/env python3
"""DBOPL 초기화 테이블 생성기: 원본(FP) DBOPL 로 계산한 상수를 C include 로 덤프한다 (런타임에서 부동소수점/수학 라이브러리를 없애기 위함).
  - kSine512[512]  : WaveTable[0x200+i]  (sin 반파)
  - kMul384[384]   : MulTable
  - kRates[]       : 지원 샘플레이트별 Chip::Setup(rate) 결과 (noiseAdd/lfoAdd/freqMul[16]/linearRates[76]/attackRates[62])
호스트(MinGW) 32bit 빌드의 FP 결과를 기준으로 하며, 16bit 빌드가 이것과 PCM 해시가 같음을 별도 검증한다.
usage: gen_tables.py <out.inc> [rate ...]"""
import sys, os, subprocess, shutil
out = os.path.abspath(sys.argv[1])
rates = [int(x) for x in sys.argv[2:]] or [8000, 8192, 11025, 16000, 22050]   # 8192 = RTC periodic-interrupt clock (/RTC)
here = os.path.dirname(os.path.abspath(__file__)); root = os.path.dirname(here)
work = os.path.join(root, 'build', 'gen', 'dump')
subprocess.check_call([sys.executable, os.path.join(here, 'gen_dbopl32.py'), os.path.join(root, 'ref', 'VSBHDA', 'src'), work])

dump = r'''
#include <stdio.h>
using namespace DBOPL;
extern "C" void eopl_dump(const char *path, const unsigned *rates, int nrates)
{
    FILE *f = fopen(path, "w");
    int i, r;
    { Chip c(false); c.Setup(22050); }                       /* force InitTables() */
    fprintf(f, "/* GENERATED by tools/gen_tables.py from the floating-point DBOPL - do not edit */\n");
    fprintf(f, "static const int16_t kSine512[512] = {");
    for (i = 0; i < 512; i++) fprintf(f, "%s%d,", (i %% 16) ? "" : "\n", (int)WaveTable[0x200 + i]);
    fprintf(f, "\n};\nstatic const uint16_t kMul384[384] = {");
    for (i = 0; i < 384; i++) fprintf(f, "%s%u,", (i %% 16) ? "" : "\n", (unsigned)MulTable[i]);
    fprintf(f, "\n};\nstruct RateSet { uint32_t rate, noiseAdd, lfoAdd, freqMul[16], linearRates[76], attackRates[62]; };\n");
    fprintf(f, "#define EOPL_NRATES %d\nstatic const RateSet kRates[EOPL_NRATES] = {\n", nrates);
    for (r = 0; r < nrates; r++) {
        Chip c(false); c.Setup(rates[r]);
        fprintf(f, "{ %u, %uUL, %uUL,\n {", rates[r], (unsigned)c.noiseAdd, (unsigned)c.lfoAdd);
        for (i = 0; i < 16; i++) fprintf(f, "%s%uUL", i ? "," : "", (unsigned)c.freqMul[i]);
        fprintf(f, "},\n {");
        for (i = 0; i < 76; i++) fprintf(f, "%s%s%uUL", i ? "," : "", (i %% 8) ? "" : "\n", (unsigned)c.linearRates[i]);
        fprintf(f, "},\n {");
        for (i = 0; i < 62; i++) fprintf(f, "%s%s%uUL", i ? "," : "", (i %% 8) ? "" : "\n", (unsigned)c.attackRates[i]);
        fprintf(f, "} },\n");
    }
    fprintf(f, "};\n");
    fclose(f);
}
'''.replace('%%', '%')
cpp = os.path.join(work, 'DBOPL.CPP')
open(cpp, 'a', encoding='latin-1').write(dump)
main = os.path.join(work, 'dump_main.cpp')
open(main, 'w').write('extern "C" void eopl_dump(const char*, const unsigned*, int);\nint main(int, char**)\n{ static const unsigned r[] = {%s}; eopl_dump("%s", r, %d); return 0; }\n'
                      % (','.join(str(x) for x in rates), out.replace('\\', '/'), len(rates)))
exe = os.path.join(work, 'dump.exe')
cf = ['g++', '-std=c++14', '-O1', '-m32', '-fno-strict-aliasing', '-fno-exceptions', '-fno-rtti', '-w', '-I', work, cpp, main, '-o', exe]
subprocess.check_call(cf)
subprocess.check_call([exe])
print('tables written: %s (rates %s)' % (out, rates))
