/* E-ray DOS OPL Emulator - OPL core API, PC speaker PCM driver API */
#ifndef PCSPK_H
#define PCSPK_H
#include "opl_core.h"

typedef void (*pcspk_pcm_cb)(s16 *dst, u32 n);   /* produce n mono s16 samples */

typedef struct {                  /* NOTE: new fields are only ever appended (test programs read a prefix of this struct) */
    u32 T;            /* PIT ticks per sample (1193182/rate)  */
    u32 isr_count;    /* IRQ count while running              */
    u32 underruns;    /* ISR found the ring empty (held last sample) */
    u32 refills;      /* chunk refills done by the foreground pump */
    u32 assists;      /* chunks generated by the ISR (foreground starved) */
    u32 clips;        /* samples clipped by the software gain */
    u32 istack_used;  /* bytes of the ISR stack touched so far (updated by pcspk_stats()) */
    u32 levels;       /* usable PWM levels (T-1)              */
    /* --- diagnostics (16-bit build) --- */
    u32 clock_rtc;    /* 1 = sample clock is the RTC periodic interrupt (IRQ8, 8192 Hz), 0 = PIT channel 0 */
    u32 pit0_samples; /* number of PIT ch0 read-backs done by the ISR (diag mode, PIT clock only) */
    u32 pit0_max;     /* largest ch0 counter value seen; > T means somebody reprogrammed PIT ch0 with a slower rate */
    u32 pit0_status;  /* last ch0 read-back status byte (expected 36h-ish: mode 3, LSB+MSB) */
    u32 pit0_bad;     /* read-backs that looked reprogrammed (counter > T or mode != 3) */
    /* --- speaker guard (always on): ISR re-asserts port 61h bits 0-1 and PIT ch2 mode 0 when a game changed them --- */
    u32 guard_checks; /* guard passes */
    u32 fix61;        /* port 61h bits 0-1 had been cleared by someone -> restored */
    u32 fixpit2;      /* PIT ch2 control (mode/access) had been changed -> restored */
    u32 last61;       /* last bad 61h value seen */
    u32 last_pit2;    /* last bad ch2 status byte seen */
    u32 rtc_off;      /* RTC mode: periodic-interrupt enable (reg B bit 6) / rate had been changed -> restored */
    /* --- interrupt windows between synthesis sub-blocks (RTC clock) --- */
    u32 yields;       /* interrupt windows opened during ISR synthesis */
    u32 wstack_used;  /* bytes of the second private stack touched (OPL writes arriving inside a window) */
    u32 sub;          /* synthesis sub-block size in samples (0 = no windows) */
    /* --- sample-clock meter (RTC clock): wall time of every 8192 IRQs measured with the BIOS tick (18.2065 Hz) --- */
    u32 rate_batches; /* completed batches of 8192 IRQs */
    u32 rate_sum;     /* total BIOS ticks they took */
    u32 rate_max;     /* slowest batch (ticks); nominal batch = 18.2 ticks */
    u32 rate_min;     /* fastest batch (ticks) */
    u32 agc_gain;     /* current automatic gain (8.8 fixed point, 256 = x1); 0 = fixed gain */
} pcspk_stats_t;

void pcspk_set_sub(unsigned sub);   /* 16-bit build: sub-block size for ISR synthesis (RTC clock); 0 disables the interrupt windows. Call after open. */

void pcspk_set_gain(u32 gain_256);  /* 8.8 fixed point, 256 = x1.0; 0 = automatic gain control (16-bit build default) */

int  pcspk_open(u32 rate, int pit_mode /*0 or 3*/, pcspk_pcm_cb cb);
int  pcspk_open_rtc(int pit_mode, pcspk_pcm_cb cb);   /* 16-bit build: RTC IRQ8 periodic interrupt (8192 Hz) as the sample clock; PIT ch0 untouched */
void pcspk_set_diag(int on);                   /* 16-bit build: ISR samples PIT ch0 every 4096 IRQs to detect reprogramming (PIT clock only) */
void pcspk_pump(void);
void pcspk_lock(void);          /* hold while touching OPL state (register writes) so the ISR won't generate concurrently */
void pcspk_unlock(void);
void pcspk_set_assist(int amode, u32 achunk);  /* amode: 0 off, 1 ISR generate with IF=0 (+ private stack), (2/3: DOS/4GW prototype only); achunk: samples per ISR synthesis step */
void pcspk_set_water(unsigned low);            /* 16-bit build: ISR synthesizes whenever ring fill < low (TSR mode) */
void pcspk_oplwrite(unsigned hi, unsigned reg, unsigned val);  /* 16-bit build: OPL register write safe against the ISR (IF=0 + private stack) */
void pcspk_call_private(void (*fn)(void));     /* 16-bit build: run fn with IF=0 on the private stack (port-trap handlers) */
int  pcspk_try_close(void);                    /* 16-bit build: unhook; returns 1 (and does nothing) if someone hooked the vector after us */
int  pcspk_is_top(void);                       /* 16-bit build: 1 if our vector (INT 8 or INT 70h) still points at our ISR */
void pcspk_close(void);
const pcspk_stats_t *pcspk_stats(void);
#endif

